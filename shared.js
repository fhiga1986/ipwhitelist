(function(){
  const cv=document.getElementById('bg-canvas');
  if(!cv) return;
  // Skip the animation on small screens and for users who prefer reduced motion (saves CPU/battery, better INP on mobile)
  if(innerWidth<700||(window.matchMedia&&matchMedia('(prefers-reduced-motion: reduce)').matches)) return;
  const ctx=cv.getContext('2d');
  let W,H,pts=[],aid;
  function resize(){W=cv.width=innerWidth;H=cv.height=innerHeight;}
  function init(){pts=[];const n=Math.floor((W*H)/22000);for(let i=0;i<n;i++)pts.push({x:Math.random()*W,y:Math.random()*H,vx:(Math.random()-.5)*.2,vy:(Math.random()-.5)*.2,r:Math.random()*1+.3});}
  function draw(){
    ctx.clearRect(0,0,W,H);
    for(let i=0;i<pts.length;i++)for(let j=i+1;j<pts.length;j++){
      const dx=pts[i].x-pts[j].x,dy=pts[i].y-pts[j].y,d=Math.sqrt(dx*dx+dy*dy);
      if(d<115){ctx.beginPath();ctx.strokeStyle=`rgba(78,255,192,${(1-d/115)*.09})`;ctx.lineWidth=.5;ctx.moveTo(pts[i].x,pts[i].y);ctx.lineTo(pts[j].x,pts[j].y);ctx.stroke();}
    }
    pts.forEach(p=>{ctx.beginPath();ctx.arc(p.x,p.y,p.r,0,Math.PI*2);ctx.fillStyle='rgba(78,255,192,.28)';ctx.fill();p.x+=p.vx;p.y+=p.vy;if(p.x<0||p.x>W)p.vx*=-1;if(p.y<0||p.y>H)p.vy*=-1;});
    aid=requestAnimationFrame(draw);
  }
  resize();init();draw();
  window.addEventListener('resize',()=>{cancelAnimationFrame(aid);resize();init();draw();});
})();

