async function runLatency(){
  initLatencyGrid();
  const btn=document.getElementById('latBtn');if(!btn)return;
  btn.disabled=true;btn.textContent='Running…';
  await Promise.all(REGIONS.map((_,i)=>measureLatency(i)));
  btn.disabled=false;btn.textContent='▶ Run Again';
}

async function measureLatency(i){
  const url=REGIONS[i].url;
  const RUNS=3;let total=0,success=0;
  for(let r=0;r<RUNS;r++){
    try{const s=performance.now();await fetch(url,{method:'HEAD',mode:'no-cors',cache:'no-store'});total+=performance.now()-s;success++;}
    catch(e){total+=5000;}
  }
  const ms=success?Math.round(total/RUNS):null;
  const el=document.getElementById('lat-'+i);
  const msel=document.getElementById('latms-'+i);
  const bar=document.getElementById('latbar-'+i);
  if(!el)return;
  if(!ms||ms>3000){
    el.textContent='timeout';el.className='latency-val slow';
    if(msel)msel.textContent='';if(bar)bar.style.width='100%';
  }else{
    const cls=ms<80?'fast':ms<200?'mid':'slow';
    el.textContent=ms;el.className='latency-val '+cls;
    if(msel)msel.textContent='ms';
    if(bar){bar.className='latency-bar-fill '+cls;bar.style.width=Math.min(100,ms/4)+'%';}
  }
}

